"""
Automated Test Generator
Generates executable, deterministic Pytest test suites targeting high-risk areas
and downstream impacted components identified by Impact Analysis.
"""

import re
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from codebase_doctor.llm_provider import BaseLLMProvider, get_llm_provider
from codebase_doctor.models import ImpactReport


class TestGenerator:
    """Generates executable pytest test suites for affected code."""
    __test__ = False

    def __init__(self, llm: Optional[BaseLLMProvider] = None):
        self.llm = llm or get_llm_provider()

    def generate_tests_for_impact(self, report: ImpactReport, output_dir: Optional[Path] = None) -> Tuple[str, Path]:
        """
        Generates pytest test suite code based on the impact report.
        Returns: (test_code_string, file_path)
        """
        target_file = report.target_file
        target_path = Path(target_file)
        target_ext = target_path.suffix.lower()
        target_stem = target_path.stem
        sanitized_stem = re.sub(r"[^a-zA-Z0-9_]", "_", target_stem)
        target_name = (
            report.target_symbols[0]
            if report.target_symbols
            else target_stem
        )

        if target_ext in {".py", ".pyw"}:
            test_code = self._build_deterministic_test_suite(
                mod_name=target_stem,
                target_name=target_name,
                suggested_tests=report.suggested_tests,
                risk_areas=report.risk_areas,
                affected_components=[c.symbol_name for c in report.affected_components],
            )
        else:
            test_code = self._build_polyglot_test_suite(
                target_file=target_file,
                target_name=target_name,
                suggested_tests=report.suggested_tests,
                risk_areas=report.risk_areas,
                affected_components=[c.symbol_name for c in report.affected_components],
            )

        test_file_name = f"test_generated_{sanitized_stem}.py"
        if output_dir:
            out_path = output_dir / test_file_name
        else:
            out_path = Path("tests") / test_file_name

        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(test_code, encoding="utf-8")

        return test_code, out_path

    def _build_deterministic_test_suite(
        self,
        mod_name: str,
        target_name: str,
        suggested_tests: List[str],
        risk_areas: List[str],
        affected_components: List[str],
    ) -> str:
        """Constructs an executable, self-contained pytest file with mocks and assertions."""
        header = f'''"""
Automated Regression & Risk Test Suite for {target_name}
Auto-generated by AI Codebase Doctor.
Target: {mod_name}.py
Risk Areas: {", ".join(risk_areas)}
"""

import sys
import unittest
from decimal import Decimal
from unittest.mock import MagicMock, patch
import pytest

# Ensure repository root is on Python sys.path
import os
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

try:
    import {mod_name}
    from {mod_name} import *
except ImportError:
    pass
'''

        test_functions = []

        for test_name in suggested_tests:
            func_code = self._generate_test_body(test_name, mod_name, target_name)
            test_functions.append(func_code)

        footer = '''
if __name__ == "__main__":
    pytest.main(["-v", __file__])
'''

        return header + "\n" + "\n\n".join(test_functions) + "\n" + footer

